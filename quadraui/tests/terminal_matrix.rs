//! Generated terminal compatibility matrix (quadraui#829, "Terminal-honest
//! #5"). Read this when:
//!
//! - you're adding a new terminal-protocol pty fixture to
//!   `tests/tui_pty_smoke.rs` and want to know how to get it into the
//!   published matrix;
//! - `readme_terminal_matrix_matches_generated` (below) is failing in CI and
//!   you need to know how to fix it (see that test's panic message — it
//!   names the exact command);
//! - you're deciding whether a multiplexer/colour-depth/mouse-mode/
//!   key-protocol combination is something quadraui actually verifies, or
//!   just claims.
//!
//! ## Why this exists
//!
//! quadraui#787's Terminal-honest epic exists because a terminal feature
//! that "should" work and a terminal feature that is *observed* to work are
//! different claims, and conflating them is how #293 (SGR mouse leaking
//! into input), #826 (unconditional truecolor on a 256-colour terminal) and
//! #827 (kitty protocol flags never checked) all shipped silently broken.
//! `tests/tui_pty_smoke.rs` closes that gap for a handful of
//! multiplexer/colour-depth/mouse-mode/key-protocol combinations by
//! spawning a real example binary in a real pty and reading the literal
//! bytes it emits. This file turns *that* — the actual, checked-in pty
//! fixtures — into a published table, instead of a claim someone typed by
//! hand into the README (see quadraui#798, which exists because a
//! hand-written doc drifted from the code it described).
//!
//! ## How "generated" is enforced here
//!
//! Three things anchor every row to something mechanically checkable,
//! rather than to a sentence a human could get wrong and never notice:
//!
//! 1. Every [`Status::Verified`] row names the exact `fn` in
//!    `tests/tui_pty_smoke.rs` that backs it
//!    (`every_verified_rows_test_fn_exists_in_the_pty_tier` greps the real
//!    source for it — a renamed/removed pty test fails this file, not just
//!    silently going stale).
//! 2. [`quadraui::ColorDepth`]'s three variants are matched exhaustively
//!    (no wildcard arm) against this matrix's colour-depth rows
//!    (`every_colordepth_variant_has_a_verified_matrix_row`) — a fourth
//!    variant is a compile error here until the matrix grows a row for it.
//! 3. `readme_terminal_matrix_matches_generated` regenerates the table from
//!    [`all_rows`] and fails if the committed block between the
//!    `TERMINAL_MATRIX` markers in the root `README.md` differs by so much
//!    as a character — the same guard shape `tests/readme_truth.rs` (#798)
//!    uses for the rest of the README.
//!
//! What this cannot do: notice a terminal-protocol claim this file's author
//! never thought to add a row for. It only keeps the rows that exist
//! honest — extend [`all_rows`] (and the pty tier itself) when a new
//! combination gets a real fixture.
//!
//! ## Regenerating the README block
//!
//! ```sh
//! cargo test -p quadraui --test terminal_matrix -- --ignored print_terminal_matrix --nocapture
//! ```
//!
//! Replace everything between `<!-- TERMINAL_MATRIX:START -->` and
//! `<!-- TERMINAL_MATRIX:END -->` in the root `README.md` with that
//! command's output, verbatim. Never hand-edit the table itself — that is
//! exactly the drift this file exists to prevent.

use std::fs;
use std::path::PathBuf;

/// Repo root — `quadraui/`'s parent, where the root `README.md` lives.
fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("quadraui crate dir always has a parent (the repo root)")
        .to_path_buf()
}

/// `quadraui/`'s own crate dir (this test's `CARGO_MANIFEST_DIR`).
fn crate_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn read(path: PathBuf) -> String {
    fs::read_to_string(&path).unwrap_or_else(|e| panic!("failed to read {}: {e}", path.display()))
}

fn root_readme() -> String {
    read(repo_root().join("README.md"))
}

/// The pty tier's own source — the ground truth every [`Status::Verified`]
/// row is checked against.
fn pty_smoke_src() -> String {
    read(crate_root().join("tests/tui_pty_smoke.rs"))
}

/// Marks the start of the generated block inside the root `README.md`.
/// Kept as one `const` (rather than inlined at each call site) so the exact
/// text can't drift between the reader and the writer.
const MATRIX_START: &str = "<!-- TERMINAL_MATRIX:START — generated by \
    quadraui/tests/terminal_matrix.rs (quadraui#829); do not hand-edit, see \
    that file's module doc for how to regenerate -->";
const MATRIX_END: &str = "<!-- TERMINAL_MATRIX:END -->";

/// How a row's claim is backed. No row is ever left without one of these —
/// that's acceptance item 3 of quadraui#829 ("no blank cell implying
/// support"), enforced structurally: [`Row`] has no way to express "no
/// status".
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Status {
    /// A real `tests/tui_pty_smoke.rs` pty fixture observed this.
    Verified,
    /// Verified — as a *negative* fact, from a source or doc citation
    /// (crossterm's Windows implementation, a vendored dependency's own
    /// code) rather than a pty fixture, because no pty fixture can exist
    /// for it in this repo's CI (no Windows console host on Linux CI, etc).
    KnownUnsupported,
    /// Nobody has checked. Named honestly rather than left blank.
    Untested,
}

impl Status {
    fn label(self) -> &'static str {
        match self {
            Status::Verified => "✅ verified",
            Status::KnownUnsupported => "🚫 known-unsupported",
            Status::Untested => "❔ untested",
        }
    }
}

/// One row of the published matrix.
struct Row {
    axis: &'static str,
    condition: &'static str,
    status: Status,
    /// For [`Status::Verified`] rows: the exact `fn` name in
    /// `tests/tui_pty_smoke.rs` this row rests on. `None` for
    /// `KnownUnsupported`/`Untested` rows, which cite a doc/source instead
    /// (see `verified_by`).
    test_fn: Option<&'static str>,
    /// The `Verified by` column's free text: `module::test_fn` for a
    /// `Verified` row (kept in sync with `test_fn` by
    /// `every_verified_rows_test_fn_exists_in_the_pty_tier`), or a citation
    /// for why the row isn't pty-verified.
    verified_by: &'static str,
}

