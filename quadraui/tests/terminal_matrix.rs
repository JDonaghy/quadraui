/// Every row in the published matrix, in table order.
fn all_rows() -> Vec<Row> {
    let mut rows = Vec::new();
    rows.extend(multiplexer_rows());
    rows.extend(color_depth_rows());
    rows.extend(mouse_mode_rows());
    rows.extend(kitty_protocol_rows());
    rows
}

/// Render `rows` as the exact markdown table this file publishes into the
/// root `README.md`.
fn render_matrix(rows: &[Row]) -> String {
    let mut out = String::new();
    out.push_str("| Axis | Condition | Status | Verified by |\n");
    out.push_str("|---|---|---|---|\n");
    for row in rows {
        out.push_str(&format!(
            "| {} | {} | {} | {} |\n",
            row.axis,
            row.condition,
            row.status.label(),
            row.verified_by
        ));
    }
    out
}

#[test]
fn every_verified_rows_test_fn_exists_in_the_pty_tier() {
    let src = pty_smoke_src();
    for row in all_rows() {
        if row.status != Status::Verified {
            continue;
        }
        let name = row.test_fn.unwrap_or_else(|| {
            panic!(
                "matrix row {:?} ({:?}) is Status::Verified but has no test_fn — every \
                 Verified row must name the pty test that backs it",
                row.axis, row.condition
            )
        });
        let needle = format!("fn {name}(");
        assert!(
            src.contains(&needle),
            "matrix row {:?} ({:?}) claims verification by `{name}`, but \
             tests/tui_pty_smoke.rs has no `fn {name}(` — the pty test was renamed or \
             removed. Update this matrix (and README.md's generated block — see this \
             file's module doc) in the same PR that changes the pty tier.",
            row.axis,
            row.condition
        );
    }
}

#[test]
fn every_colordepth_variant_has_a_verified_matrix_row() {
    // Exhaustive match — no wildcard arm — over `quadraui::ColorDepth`. A
    // fourth variant is a compile error here, which is what forces this
    // matrix to grow a row for it in the same PR rather than silently
    // describing only three of four depths forever.
    fn expected_test_fn(d: quadraui::ColorDepth) -> &'static str {
        use quadraui::ColorDepth::*;
        match d {
            Ansi16 => "tui_pipeline_under_plain_xterm_emits_ansi16_sgr",
            Indexed256 => "tui_pipeline_under_256color_term_emits_indexed_sgr_not_truecolor",
            TrueColor => "tui_pipeline_with_colorterm_truecolor_is_byte_identical_to_before",
        }
    }
    let rows = all_rows();
    for expected in [
        expected_test_fn(quadraui::ColorDepth::Ansi16),
        expected_test_fn(quadraui::ColorDepth::Indexed256),
        expected_test_fn(quadraui::ColorDepth::TrueColor),
    ] {
        assert!(
            rows.iter()
                .any(|r| r.status == Status::Verified && r.test_fn == Some(expected)),
            "no Verified matrix row cites `{expected}` — a ColorDepth variant is missing \
             its colour-depth row"
        );
    }
}

#[test]
fn readme_terminal_matrix_matches_generated() {
    let readme = root_readme();
    let start = readme.find(MATRIX_START).unwrap_or_else(|| {
        panic!(
            "root README.md is missing the `{MATRIX_START}` marker — the generated \
             terminal compatibility matrix (quadraui#829) has nowhere to go. Add both \
             markers (see quadraui/tests/terminal_matrix.rs's module doc) and re-run this \
             test to see the block to paste between them."
        )
    });
    let after_start = start + MATRIX_START.len();
    let end = readme[after_start..].find(MATRIX_END).unwrap_or_else(|| {
        panic!(
            "root README.md has a `{MATRIX_START}` marker but no matching \
             `{MATRIX_END}` — add the closing marker."
        )
    }) + after_start;

    let committed = readme[after_start..end].trim();
    let generated = render_matrix(&all_rows());

    assert_eq!(
        committed,
        generated.trim(),
        "README.md's terminal compatibility matrix (between the TERMINAL_MATRIX markers) \
         does not match what quadraui/tests/terminal_matrix.rs generates from the pty \
         tier's actual tests. Regenerate it — never hand-edit the table:\n\n  cargo test \
         -p quadraui --test terminal_matrix -- --ignored print_terminal_matrix --nocapture\n\n\
         — then replace everything between the markers with that command's output, \
         verbatim. This is the same drift quadraui#798 exists to prevent for the rest of \
         the README (see tests/readme_truth.rs)."
    );
}

