#!/usr/bin/env python3
"""Generates typed wire definitions for `quadraui-py`/`quadraui-node`: Python
`.pyi` stubs (`quadraui-py/python/quadraui/wire.pyi`) and TypeScript ambient
declarations (`quadraui-node/js/wire.d.ts`) for every layout-tree node, leaf
descriptor, and `UiEvent`/activation shape a binding's wire format accepts
or emits.

The schema itself lives in Rust, not here: [`load_defs_from_rust`] shells
out to `quadraui-binding-core`'s `export_wire_schema` binary (built from
`quadraui-binding-core/src/wire_schema.rs`) and decodes its JSON dump into
this script's own [`Ty`]/[`Field`]/[`ObjDef`]/[`AliasDef`] objects. This
module owns exactly two things: that JSON decode, and rendering the decoded
definitions into the two target languages ([`render_python`]/
[`render_typescript`]) -- never the definitions' own shape. That split is
what makes the Rust side the actual source of truth: a field or variant
added on the Rust side without a matching `wire_schema.rs` update fails to
compile under `cargo test`/`cargo check --tests` (see that module's own
`coverage` guards, which live in a `#[cfg(test)]` module and so are not
reached by a bare `cargo build`/`cargo check`), and a `wire_schema.rs`
update that isn't reflected here is caught by `--check` below.

Every additive "extra" primitive kind (registered in
`quadraui-binding-core/src/extra_paint.rs`'s `extra_primitives!` table) is
narrowed field-by-field in `wire_schema.rs`, which lists every one of them
by reading `EXTRA_PRIMITIVE_KINDS` directly, so a new kind is never missed.

Usage:

    python3 scripts/gen_wire_types.py          # (re)generate both outputs
    python3 scripts/gen_wire_types.py --check  # exit 1 if generation would
                                                # change either committed file
"""

from __future__ import annotations

import argparse
import json
import keyword
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Optional, Sequence, Tuple

REPO_ROOT = Path(__file__).resolve().parent.parent
PY_OUT = REPO_ROOT / "quadraui-py" / "python" / "quadraui" / "wire.pyi"
TS_OUT = REPO_ROOT / "quadraui-node" / "js" / "wire.d.ts"

GENERATED_BANNER = (
    "Generated by `scripts/gen_wire_types.py` from the wire schema in "
    "`quadraui-binding-core/src/wire_schema.rs` -- do not hand-edit; re-run "
    "that script instead."
)


# ─── A tiny two-target type expression (Python stub + TypeScript ambient) ──


@dataclass(frozen=True)
class Ty:
    """One type expression, pre-rendered for both targets at construction
    time -- there is no shared AST to walk twice, just two parallel strings
    kept in lockstep by the constructors below."""

    py: str
    ts: str


def REF(name: str) -> Ty:
    return Ty(name, name)


STR = Ty("str", "string")
INT = Ty("int", "number")
FLOAT = Ty("float", "number")
BOOL = Ty("bool", "boolean")
ANY = Ty("Any", "unknown")


def _ts_wrap(t: Ty) -> str:
    """Parenthesizes `t`'s TS rendering when it contains a top-level union/
    intersection -- composing it into `T[]`/`T | null` unparenthesized would
    silently change what the union applies to."""
    if " | " in t.ts or " & " in t.ts:
        return f"({t.ts})"
    return t.ts


def NULLABLE(t: Ty) -> Ty:
    """The value may be `None`/`null`, but the *key* is still required --
    distinct from [`Field.optional`], which controls whether the key may be
    omitted. This is stricter than the actual Rust decode: serde's derive
    routes a missing field through `Deserialize::deserialize` on `none`,
    which `Option<T>` always accepts, so an `Option<T>` field decodes fine
    whether the wire dict omits the key entirely or carries it set to
    `null` -- `#[serde(default)]` isn't needed either way. [`NULLABLE`]
    (rather than [`Field.optional`]) is still the right default for most
    `Option<T>` fields here because this repo's own house style always
    writes the explicit `None`/`null` (see `quadraui-py/tests/
    test_descriptors.py` and `quadraui-py/examples/file_manager.py`) --
    reach for `optional=True` instead when a field is genuinely meant to be
    omittable on the wire, not just nullable."""
    return Ty(f"Optional[{t.py}]", f"{_ts_wrap(t)} | null")


def LIST(t: Ty) -> Ty:
    return Ty(f"List[{t.py}]", f"{_ts_wrap(t)}[]")


def DICTT(k: Ty, v: Ty) -> Ty:
    return Ty(f"Dict[{k.py}, {v.py}]", f"Record<{k.ts}, {v.ts}>")


def TUP(*items: Ty) -> Ty:
    return Ty(
        f"Tuple[{', '.join(i.py for i in items)}]",
        f"[{', '.join(i.ts for i in items)}]",
    )


def LIT(*values: str) -> Ty:
    return Ty(
        f"Literal[{', '.join(repr(v) for v in values)}]",
        " | ".join(json.dumps(v) for v in values),
    )


def UNIONT(*items: Ty) -> Ty:
    return Ty(
        f"Union[{', '.join(i.py for i in items)}]",
        " | ".join(_ts_wrap(i) for i in items),
    )


# ─── Definitions ────────────────────────────────────────────────────────────


@dataclass
class Field:
    name: str
    ty: Ty
    optional: bool = False  # key may be omitted (`#[serde(default...)]`)
    doc: str = ""


@dataclass
class ObjDef:
    """One `TypedDict`/`interface`: either an ordinary struct (some fields
    required, some [`Field.optional`]) or a flat, all-optional "one of these
    keys is present" shape -- [`Field.optional`] on every field -- used for
    every tagged union a binding *reads* (an activation payload, `UiEvent`
    itself) so `"Tag" in value` narrows the way `quadraui-py/examples/
    file_manager.py`'s own event handler already does. A tagged union a
    binding only *writes* (a layout-tree node, a `ToolbarButton`) instead
    gets one [`ObjDef`] per variant, combined into a [`union_of`] below --
    stricter for construction, since a dict literal checked against a
    `Union` of single-required-key members rejects two tags set at once,
    which a shared flat object (every key optional) would silently accept."""

    name: str
    fields: List[Field]
    doc: str = ""
    # True for a [`flat`]-built discriminated union: every field is
    # optional and mutually exclusive in practice (exactly one key is ever
    # present on the wire). Python's `TypedDict`+`NotRequired` narrows a
    # single such object correctly via `"Tag" in value` (verified: mypy
    # treats a `NotRequired` key's absence as excluding it from the
    # narrowed type) -- but TypeScript's `in` narrowing on one interface
    # with optional (`?:`) properties does *not* drop the `| undefined`
    # half of an optional property's type, even once its key is proven
    # present (`tsc --strict` still flags `x.Tree` as possibly `undefined`
    # after `"Tree" in x`). TypeScript only narrows properly across a
    # `Union` of *separate* object types where each carries its one key as
    # non-optional -- so [`render_typescript`] renders a `discriminated`
    # [`ObjDef`] as exactly that union instead of as one `interface`,
    # while [`render_python`] keeps rendering every [`ObjDef`] (flat or
    # not) as one `TypedDict`.
    discriminated: bool = False
    # Extra fields present alongside whichever tag [`discriminated`] member
    # is set -- not a tag of their own. [`render_python`] folds these into
    # the same `TypedDict` as every other field (already how a flat object
    # works); [`render_typescript`] has to splice them into *each* union
    # member's object-type literal instead, since a `discriminated` union
    # has no single interface to add an optional property to. Every
    # `common` field should itself be [`Field.optional`] -- it is never
    # part of what makes a tag's payload well-formed.
    common: List[Field] = field(default_factory=list)


@dataclass
class AliasDef:
    name: str
    ty: Ty
    doc: str = ""


Def = object  # ObjDef | AliasDef, kept loose to avoid importing Union twice


def flat(
    name: str,
    variants: Sequence[Tuple[str, Ty]],
    doc: str = "",
    common: Sequence[Field] = (),
) -> ObjDef:
    """An [`ObjDef`] with one optional [`Field`] per `(tag, payload_type)`
    pair -- see [`ObjDef`]'s own doc for when to reach for this over a
    per-variant [`UnionDef`]. `common` (see [`ObjDef.common`]) is for a key
    that can ride alongside whichever tag is set, not a tag of its own."""
    return ObjDef(
        name,
        [Field(tag, ty, optional=True) for tag, ty in variants],
        doc,
        discriminated=True,
        common=list(common),
    )


def union_of(name: str, members: Sequence[Ty], doc: str = "") -> AliasDef:
    return AliasDef(name, UNIONT(*members), doc)


# `None` until [`load_defs_from_rust`] populates it (lazily, from `main`) --
# never built eagerly at import time, so importing this module for its
# renderer/builder helpers alone (as `scripts/test_gen_wire_types.py` does)
# never shells out to `cargo`. A test that wants `main`/`_def_from_json` to
# see a specific schema monkeypatches this directly, bypassing
# [`load_defs_from_rust`] entirely.
DEFS: Optional[List[Def]] = None


# ─── Decoding the Rust-exported JSON into this script's own `Ty`/`Def` ─────


def _ty_from_json(obj: dict) -> Ty:
    """Decodes one `TyJson` value (`quadraui-binding-core/src/wire_schema.rs`)
    into this script's own [`Ty`] -- the abstract type expression, not a
    pre-rendered string; [`render_python`]/[`render_typescript`] still own
    every target-language rendering/parenthesization rule."""
    kind = obj["kind"]
    if kind == "prim":
        return {"STR": STR, "INT": INT, "FLOAT": FLOAT, "BOOL": BOOL, "ANY": ANY}[obj["name"]]
    if kind == "ref":
        return REF(obj["name"])
    if kind == "nullable":
        return NULLABLE(_ty_from_json(obj["inner"]))
    if kind == "list":
        return LIST(_ty_from_json(obj["inner"]))
    if kind == "dict":
        return DICTT(_ty_from_json(obj["key"]), _ty_from_json(obj["value"]))
    if kind == "tuple":
        return TUP(*[_ty_from_json(i) for i in obj["items"]])
    if kind == "lit":
        return LIT(*obj["values"])
    if kind == "union":
        return UNIONT(*[_ty_from_json(i) for i in obj["items"]])
    raise ValueError(f"unknown TyJson kind: {kind!r}")


def _field_from_json(obj: dict) -> Field:
    return Field(
        obj["name"],
        _ty_from_json(obj["ty"]),
        optional=obj.get("optional", False),
        doc=obj.get("doc", ""),
    )


def _def_from_json(obj: dict) -> Def:
    """Decodes one `DefJson` value into this script's own [`ObjDef`]/
    [`AliasDef`]."""
    kind = obj["kind"]
    if kind == "obj":
        return ObjDef(
            obj["name"],
            [_field_from_json(f) for f in obj["fields"]],
            obj.get("doc", ""),
            discriminated=obj.get("discriminated", False),
            common=[_field_from_json(f) for f in obj.get("common", [])],
        )
    if kind == "alias":
        return AliasDef(obj["name"], _ty_from_json(obj["ty"]), obj.get("doc", ""))
    raise ValueError(f"unknown DefJson kind: {kind!r}")


def load_defs_from_rust() -> List[Def]:
    """Runs `quadraui-binding-core`'s `export_wire_schema` binary (built
    from `quadraui-binding-core/src/wire_schema.rs`, the Rust-side schema
    this whole module renders) and decodes its JSON dump into this script's
    own `Ty`/`Field`/`ObjDef`/`AliasDef` objects, in the same order the
    Rust side returned them.

    This is the one step that makes the Rust side the actual source of
    truth: this script never constructs the schema itself, only whatever
    shape `cargo run` reports right now. A field or variant added to a
    wire-decoded Rust type without a matching `wire_schema.rs` update fails
    to compile under `cargo test`/`cargo check --tests`
    (`wire_schema.rs`'s own `coverage` module), and a `wire_schema.rs`
    update that isn't reflected in the committed `.pyi`/`.d.ts` fails
    `--check` below.
    """
    proc = subprocess.run(
        ["cargo", "run", "--quiet", "-p", "quadraui-binding-core", "--bin", "export_wire_schema"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        raise RuntimeError(
            "failed to export the wire schema from "
            "`quadraui-binding-core` -- see cargo's output above"
        )
    raw: List[dict] = json.loads(proc.stdout)
    return [_def_from_json(d) for d in raw]


def get_defs() -> List[Def]:
    """[`DEFS`], populating it via [`load_defs_from_rust`] on first use."""
    global DEFS
    if DEFS is None:
        DEFS = load_defs_from_rust()
    return DEFS


# ─── Rendering ──────────────────────────────────────────────────────────────


def render_python(defs: List[Def]) -> str:
    lines = [
        '"""Typed wire shapes for every layout-tree node, leaf descriptor, and',
        "`UiEvent`/activation a `QuiApp`/`QuiShellApp` render or event callback",
        "exchanges with the native extension -- see `scripts/gen_wire_types.py`",
        "for how this file is produced and what it deliberately leaves untyped.",
        "",
        "This module has no runtime body beyond these declarations: every name",
        "is a `TypedDict`/alias meant for a type checker, not a value an app",
        "constructs by calling into this module. Import it only inside",
        "`if TYPE_CHECKING:` (or quote the name in a string annotation) --",
        "`quadraui.wire` is a stub-only module (no backing `.py`), so an",
        "unconditional runtime `from quadraui.wire import X` raises",
        "`ModuleNotFoundError`.",
        "",
        f"{GENERATED_BANNER}",
        '"""',
        "",
        "from typing import Any, Dict, List, Literal, Optional, Tuple, Union",
        "from typing_extensions import NotRequired, TypedDict",
        "",
    ]
    for d in defs:
        if isinstance(d, AliasDef):
            if d.doc:
                lines.append(f"# {d.doc}")
            lines.append(f"{d.name} = {d.ty.py}")
            lines.append("")
        elif isinstance(d, ObjDef):
            all_fields = (*d.fields, *d.common)
            # A wire field name is a Rust struct/variant field (or, for a
            # `flat()`-built dict, the Rust variant tag itself) -- nothing
            # stops either from colliding with a Python keyword (`from` on
            # `DrawOp::Line`/`Bezier`/`DashedLine`, say), which the
            # class-based `TypedDict` syntax below can't express at all
            # (`class X: from: Y` is a `SyntaxError`, keyword status is a
            # property of the identifier position, not escapable the way
            # `from_` or a raw string would be). The *functional* form
            # (`X = TypedDict("X", {...})`) takes the field names as
            # ordinary dict string keys instead, so it has no such
            # restriction -- reach for it only when a class body actually
            # can't say what's needed, since the class form is more
            # readable and keeps editor rename/go-to-definition working.
            if any(keyword.iskeyword(f.name) for f in all_fields):
                lines.append(f"{d.name} = TypedDict(")
                lines.append(f'    "{d.name}",')
                lines.append("    {")
                for f in all_fields:
                    ty = f"NotRequired[{f.ty.py}]" if f.optional else f.ty.py
                    lines.append(f'        "{f.name}": {ty},')
                lines.append("    },")
                lines.append(")")
                if d.doc:
                    lines.append(f'"""{d.doc}"""')
                lines.append("")
                continue
            lines.append(f"class {d.name}(TypedDict):")
            if d.doc:
                lines.append(f'    """{d.doc}"""')
            if not d.fields and not d.common:
                lines.append("    pass")
            for f in all_fields:
                ty = f"NotRequired[{f.ty.py}]" if f.optional else f.ty.py
                comment = f"  # {f.doc}" if f.doc else ""
                lines.append(f"    {f.name}: {ty}{comment}")
            lines.append("")
        else:  # pragma: no cover - exhaustive by construction
            raise TypeError(f"unknown def kind: {d!r}")
    return "\n".join(lines).rstrip() + "\n"


def render_typescript(defs: List[Def]) -> str:
    lines = [
        "// Typed wire shapes for every layout-tree node, leaf descriptor, and",
        "// `UiEvent`/activation a `QuiApp`/`QuiShellApp` render or event callback",
        "// exchanges with the native addon -- see `scripts/gen_wire_types.py` for",
        "// how this file is produced and what it deliberately leaves untyped.",
        "//",
        "// Every export here is `export type`/`export interface` -- erasable, no",
        "// runtime value -- so importing from this module costs nothing at",
        "// runtime even though Node's native TypeScript support strips rather",
        "// than compiles `.ts` (see `index.ts`'s own header comment).",
        "//",
        f"// {GENERATED_BANNER}",
        "",
    ]
    for d in defs:
        if isinstance(d, AliasDef):
            if d.doc:
                lines.append(f"/** {d.doc} */")
            lines.append(f"export type {d.name} = {d.ty.ts};")
            lines.append("")
        elif isinstance(d, ObjDef) and d.discriminated:
            # See `ObjDef.discriminated`'s doc: a union of single-required-
            # key object types, not one interface with optional properties
            # -- the shape TS's `"Tag" in value` actually narrows on.
            if d.doc:
                lines.append(f"/** {d.doc} */")
            common_ts = "".join(
                f" {cf.name}{'?' if cf.optional else ''}: {cf.ty.ts};" for cf in d.common
            )
            members = " | ".join(f"{{ {f.name}: {f.ty.ts};{common_ts} }}" for f in d.fields)
            lines.append(f"export type {d.name} = {members};")
            lines.append("")
        elif isinstance(d, ObjDef):
            if d.doc:
                lines.append(f"/** {d.doc} */")
            lines.append(f"export interface {d.name} {{")
            for f in d.fields:
                comment = f" // {f.doc}" if f.doc else ""
                lines.append(f"  {f.name}{'?' if f.optional else ''}: {f.ty.ts};{comment}")
            lines.append("}")
            lines.append("")
        else:  # pragma: no cover - exhaustive by construction
            raise TypeError(f"unknown def kind: {d!r}")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if (re)generating would change either committed file, "
        "without writing anything",
    )
    args = parser.parse_args(argv)

    defs = get_defs()
    py_text = render_python(defs)
    ts_text = render_typescript(defs)

    if args.check:
        stale = []
        for path, text in ((PY_OUT, py_text), (TS_OUT, ts_text)):
            current = path.read_text() if path.exists() else None
            if current != text:
                stale.append(path)
        if stale:
            for path in stale:
                print(f"stale: {path.relative_to(REPO_ROOT)}", file=sys.stderr)
            print(
                "wire types are out of date -- run "
                "`python3 scripts/gen_wire_types.py` and commit the result",
                file=sys.stderr,
            )
            return 1
        print("wire types are up to date")
        return 0

    PY_OUT.write_text(py_text)
    TS_OUT.write_text(ts_text)
    print(f"wrote {PY_OUT.relative_to(REPO_ROOT)}")
    print(f"wrote {TS_OUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
