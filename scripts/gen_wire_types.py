#!/usr/bin/env python3
"""Generates typed wire definitions for `quadraui-py`/`quadraui-node`: Python
`.pyi` stubs (`quadraui-py/python/quadraui/wire.pyi`, `quadraui-py/python/
quadraui/_quadraui.pyi`) and TypeScript ambient declarations
(`quadraui-node/js/wire.d.ts`) for every layout-tree node, leaf descriptor,
`UiEvent`/activation shape, and native-extension method a binding's wire
format accepts or emits.

The wire *data* schema lives in Rust, not here: [`load_defs_from_rust`]
shells out to `quadraui-binding-core`'s `export_wire_schema` binary (built
from `quadraui-binding-core/src/wire_schema.rs`) and decodes its JSON dump
into this script's own [`Ty`]/[`Field`]/[`ObjDef`]/[`AliasDef`] objects. This
module owns exactly two things: that JSON decode, and rendering the decoded
definitions into the two target languages ([`render_python`]/
[`render_typescript`]) -- never the definitions' own shape. That split is
what makes the Rust side the actual source of truth: a field or variant
added on the Rust side without a matching `wire_schema.rs` update fails to
compile under `cargo test`/`cargo check --tests` (see that module's own
`coverage` guards, which live in a `#[cfg(test)]` module and so are not
reached by a bare `cargo build`/`cargo check`), and a `wire_schema.rs`
update that isn't reflected here is caught by `--check` below.

Every additive "extra" primitive kind (registered in
`quadraui-binding-core/src/extra_paint.rs`'s `extra_primitives!` table) is
narrowed field-by-field in `wire_schema.rs`, which lists every one of them
by reading `EXTRA_PRIMITIVE_KINDS` directly, so a new kind is never missed.

The native-extension *method* surface (`_quadraui.pyi`) is sourced
differently: [`parse_pymethods`]/[`parse_pyfunctions`] parse
`quadraui-py/src/lib.rs` directly (there is no JSON export for `#[pymethods]`
the way `wire_schema.rs` provides one for wire data) -- see that section's
own comment for the parser's scope and [`PARAM_OVERRIDES`]/
[`RETURN_OVERRIDES`] for where a `&Bound<'_, PyDict>`/`PyList`/`PyAny`
argument or a pythonized `Py<PyAny>` return is narrowed to one of this
file's own `wire.pyi` `TypedDict`s instead of a bare `Mapping[str, Any]`/
`Any`. A method whose Rust type this parser can't map raises instead of
silently emitting `Any` -- the same "new shape needs a table entry" contract
`wire_schema.rs`'s own coverage guard has, so every exported method's shape
is accounted for rather than falling back to an opaque `Any`.

Usage:

    python3 scripts/gen_wire_types.py          # (re)generate all outputs
    python3 scripts/gen_wire_types.py --check  # exit 1 if generation would
                                                # change any committed file
"""

