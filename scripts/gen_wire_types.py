# ─── A tiny two-target type expression (Python stub + TypeScript ambient) ──


@dataclass(frozen=True)
class Ty:
    """One type expression, pre-rendered for both targets at construction
    time -- there is no shared AST to walk twice, just two parallel strings
    kept in lockstep by the constructors below."""

    py: str
    ts: str


def REF(name: str) -> Ty:
    return Ty(name, name)


STR = Ty("str", "string")
INT = Ty("int", "number")
FLOAT = Ty("float", "number")
BOOL = Ty("bool", "boolean")
ANY = Ty("Any", "unknown")


def _ts_wrap(t: Ty) -> str:
    """Parenthesizes `t`'s TS rendering when it contains a top-level union/
    intersection -- composing it into `T[]`/`T | null` unparenthesized would
    silently change what the union applies to."""
    if " | " in t.ts or " & " in t.ts:
        return f"({t.ts})"
    return t.ts


def NULLABLE(t: Ty) -> Ty:
    """The value may be `None`/`null`, but the *key* is still required --
    distinct from [`Field.optional`], which controls whether the key may be
    omitted. This is stricter than the actual Rust decode: serde's derive
    routes a missing field through `Deserialize::deserialize` on `none`,
    which `Option<T>` always accepts, so an `Option<T>` field decodes fine
    whether the wire dict omits the key entirely or carries it set to
    `null` -- `#[serde(default)]` isn't needed either way. [`NULLABLE`]
    (rather than [`Field.optional`]) is still the right default for most
    `Option<T>` fields here because this repo's own house style always
    writes the explicit `None`/`null` (see `quadraui-py/tests/
    test_descriptors.py` and `quadraui-py/examples/file_manager.py`) --
    reach for `optional=True` instead when a field is genuinely meant to be
    omittable on the wire, not just nullable."""
    return Ty(f"Optional[{t.py}]", f"{_ts_wrap(t)} | null")


def LIST(t: Ty) -> Ty:
    return Ty(f"List[{t.py}]", f"{_ts_wrap(t)}[]")


def DICTT(k: Ty, v: Ty) -> Ty:
    return Ty(f"Dict[{k.py}, {v.py}]", f"Record<{k.ts}, {v.ts}>")


def TUP(*items: Ty) -> Ty:
    return Ty(
        f"Tuple[{', '.join(i.py for i in items)}]",
        f"[{', '.join(i.ts for i in items)}]",
    )


def LIT(*values: str) -> Ty:
    return Ty(
        f"Literal[{', '.join(repr(v) for v in values)}]",
        " | ".join(json.dumps(v) for v in values),
    )


def UNIONT(*items: Ty) -> Ty:
    return Ty(
        f"Union[{', '.join(i.py for i in items)}]",
        " | ".join(_ts_wrap(i) for i in items),
    )


# ─── Definitions ────────────────────────────────────────────────────────────


@dataclass
class Field:
    name: str
    ty: Ty
    optional: bool = False  # key may be omitted (`#[serde(default...)]`)
    doc: str = ""


@dataclass
class ObjDef:
    """One `TypedDict`/`interface`: either an ordinary struct (some fields
    required, some [`Field.optional`]) or a flat, all-optional "one of these
    keys is present" shape -- [`Field.optional`] on every field -- used for
    every tagged union a binding *reads* (an activation payload, `UiEvent`
    itself) so `"Tag" in value` narrows the way `quadraui-py/examples/
    file_manager.py`'s own event handler already does. A tagged union a
    binding only *writes* (a layout-tree node, a `ToolbarButton`) instead
    gets one [`ObjDef`] per variant, combined into a [`union_of`] below --
    stricter for construction, since a dict literal checked against a
    `Union` of single-required-key members rejects two tags set at once,
    which a shared flat object (every key optional) would silently accept."""

    name: str
    fields: List[Field]
    doc: str = ""
    # True for a [`flat`]-built discriminated union: every field is
    # optional and mutually exclusive in practice (exactly one key is ever
    # present on the wire). Python's `TypedDict`+`NotRequired` narrows a
    # single such object correctly via `"Tag" in value` (verified: mypy
    # treats a `NotRequired` key's absence as excluding it from the
    # narrowed type) -- but TypeScript's `in` narrowing on one interface
    # with optional (`?:`) properties does *not* drop the `| undefined`
    # half of an optional property's type, even once its key is proven
    # present (`tsc --strict` still flags `x.Tree` as possibly `undefined`
    # after `"Tree" in x`). TypeScript only narrows properly across a
    # `Union` of *separate* object types where each carries its one key as
    # non-optional -- so [`render_typescript`] renders a `discriminated`
    # [`ObjDef`] as exactly that union instead of as one `interface`,
    # while [`render_python`] keeps rendering every [`ObjDef`] (flat or
    # not) as one `TypedDict`.
    discriminated: bool = False
    # Extra fields present alongside whichever tag [`discriminated`] member
    # is set -- not a tag of their own. [`render_python`] folds these into
    # the same `TypedDict` as every other field (already how a flat object
    # works); [`render_typescript`] has to splice them into *each* union
    # member's object-type literal instead, since a `discriminated` union
    # has no single interface to add an optional property to. Every
    # `common` field should itself be [`Field.optional`] -- it is never
    # part of what makes a tag's payload well-formed.
    common: List[Field] = field(default_factory=list)


@dataclass
class AliasDef:
    name: str
    ty: Ty
    doc: str = ""


Def = object  # ObjDef | AliasDef, kept loose to avoid importing Union twice


def flat(
    name: str,
    variants: Sequence[Tuple[str, Ty]],
    doc: str = "",
    common: Sequence[Field] = (),
) -> ObjDef:
    """An [`ObjDef`] with one optional [`Field`] per `(tag, payload_type)`
    pair -- see [`ObjDef`]'s own doc for when to reach for this over a
    per-variant [`UnionDef`]. `common` (see [`ObjDef.common`]) is for a key
    that can ride alongside whichever tag is set, not a tag of its own."""
    return ObjDef(
        name,
        [Field(tag, ty, optional=True) for tag, ty in variants],
        doc,
        discriminated=True,
        common=list(common),
    )


def union_of(name: str, members: Sequence[Ty], doc: str = "") -> AliasDef:
    return AliasDef(name, UNIONT(*members), doc)


# `None` until [`load_defs_from_rust`] populates it (lazily, from `main`) --
# never built eagerly at import time, so importing this module for its
# renderer/builder helpers alone (as `scripts/test_gen_wire_types.py` does)
# never shells out to `cargo`. A test that wants `main`/`_def_from_json` to
# see a specific schema monkeypatches this directly, bypassing
# [`load_defs_from_rust`] entirely.
DEFS: Optional[List[Def]] = None


# ─── Decoding the Rust-exported JSON into this script's own `Ty`/`Def` ─────


def _ty_from_json(obj: dict) -> Ty:
    """Decodes one `TyJson` value (`quadraui-binding-core/src/wire_schema.rs`)
    into this script's own [`Ty`] -- the abstract type expression, not a
    pre-rendered string; [`render_python`]/[`render_typescript`] still own
    every target-language rendering/parenthesization rule."""
    kind = obj["kind"]
    if kind == "prim":
        return {"STR": STR, "INT": INT, "FLOAT": FLOAT, "BOOL": BOOL, "ANY": ANY}[obj["name"]]
    if kind == "ref":
        return REF(obj["name"])
    if kind == "nullable":
        return NULLABLE(_ty_from_json(obj["inner"]))
    if kind == "list":
        return LIST(_ty_from_json(obj["inner"]))
    if kind == "dict":
        return DICTT(_ty_from_json(obj["key"]), _ty_from_json(obj["value"]))
    if kind == "tuple":
        return TUP(*[_ty_from_json(i) for i in obj["items"]])
    if kind == "lit":
        return LIT(*obj["values"])
    if kind == "union":
        return UNIONT(*[_ty_from_json(i) for i in obj["items"]])
    raise ValueError(f"unknown TyJson kind: {kind!r}")


def _field_from_json(obj: dict) -> Field:
    return Field(
        obj["name"],
        _ty_from_json(obj["ty"]),
        optional=obj.get("optional", False),
        doc=obj.get("doc", ""),
    )


def _def_from_json(obj: dict) -> Def:
    """Decodes one `DefJson` value into this script's own [`ObjDef`]/
    [`AliasDef`]."""
    kind = obj["kind"]
    if kind == "obj":
        return ObjDef(
            obj["name"],
            [_field_from_json(f) for f in obj["fields"]],
            obj.get("doc", ""),
            discriminated=obj.get("discriminated", False),
            common=[_field_from_json(f) for f in obj.get("common", [])],
        )
    if kind == "alias":
        return AliasDef(obj["name"], _ty_from_json(obj["ty"]), obj.get("doc", ""))
    raise ValueError(f"unknown DefJson kind: {kind!r}")


def load_defs_from_rust() -> List[Def]:
    """Runs `quadraui-binding-core`'s `export_wire_schema` binary (built
    from `quadraui-binding-core/src/wire_schema.rs`, the Rust-side schema
    this whole module renders) and decodes its JSON dump into this script's
    own `Ty`/`Field`/`ObjDef`/`AliasDef` objects, in the same order the
    Rust side returned them.

    This is the one step that makes the Rust side the actual source of
    truth: this script never constructs the schema itself, only whatever
    shape `cargo run` reports right now. A field or variant added to a
    wire-decoded Rust type without a matching `wire_schema.rs` update fails
    to compile under `cargo test`/`cargo check --tests`
    (`wire_schema.rs`'s own `coverage` module), and a `wire_schema.rs`
    update that isn't reflected in the committed `.pyi`/`.d.ts` fails
    `--check` below.
    """
    proc = subprocess.run(
        ["cargo", "run", "--quiet", "-p", "quadraui-binding-core", "--bin", "export_wire_schema"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        raise RuntimeError(
            "failed to export the wire schema from "
            "`quadraui-binding-core` -- see cargo's output above"
        )
    raw: List[dict] = json.loads(proc.stdout)
    return [_def_from_json(d) for d in raw]


def get_defs() -> List[Def]:
    """[`DEFS`], populating it via [`load_defs_from_rust`] on first use."""
    global DEFS
    if DEFS is None:
        DEFS = load_defs_from_rust()
    return DEFS


# ─── Rendering ──────────────────────────────────────────────────────────────


def render_python(defs: List[Def]) -> str:
    lines = [
        '"""Typed wire shapes for every layout-tree node, leaf descriptor, and',
        "`UiEvent`/activation a `QuiApp`/`QuiShellApp` render or event callback",
        "exchanges with the native extension -- see `scripts/gen_wire_types.py`",
        "for how this file is produced and what it deliberately leaves untyped.",
        "",
        "This module has no runtime body beyond these declarations: every name",
        "is a `TypedDict`/alias meant for a type checker, not a value an app",
        "constructs by calling into this module. Import it only inside",
        "`if TYPE_CHECKING:` (or quote the name in a string annotation) --",
        "`quadraui.wire` is a stub-only module (no backing `.py`), so an",
        "unconditional runtime `from quadraui.wire import X` raises",
        "`ModuleNotFoundError`.",
        "",
        f"{GENERATED_BANNER}",
        '"""',
        "",
        "from typing import Any, Dict, List, Literal, Optional, Tuple, Union",
        "from typing_extensions import NotRequired, TypedDict",
        "",
    ]
    for d in defs:
        if isinstance(d, AliasDef):
            if d.doc:
                lines.append(f"# {d.doc}")
            lines.append(f"{d.name} = {d.ty.py}")
            lines.append("")
        elif isinstance(d, ObjDef):
            all_fields = (*d.fields, *d.common)
            # A wire field name is a Rust struct/variant field (or, for a
            # `flat()`-built dict, the Rust variant tag itself) -- nothing
            # stops either from colliding with a Python keyword (`from` on
            # `DrawOp::Line`/`Bezier`/`DashedLine`, say), which the
            # class-based `TypedDict` syntax below can't express at all
            # (`class X: from: Y` is a `SyntaxError`, keyword status is a
            # property of the identifier position, not escapable the way
            # `from_` or a raw string would be). The *functional* form
            # (`X = TypedDict("X", {...})`) takes the field names as
            # ordinary dict string keys instead, so it has no such
            # restriction -- reach for it only when a class body actually
            # can't say what's needed, since the class form is more
            # readable and keeps editor rename/go-to-definition working.
            if any(keyword.iskeyword(f.name) for f in all_fields):
                lines.append(f"{d.name} = TypedDict(")
                lines.append(f'    "{d.name}",')
                lines.append("    {")
                for f in all_fields:
                    ty = f"NotRequired[{f.ty.py}]" if f.optional else f.ty.py
                    comment = f"  # {f.doc}" if f.doc else ""
                    lines.append(f'        "{f.name}": {ty},{comment}')
                lines.append("    },")
                lines.append(")")
                if d.doc:
                    lines.append(f'"""{d.doc}"""')
                lines.append("")
                continue
            lines.append(f"class {d.name}(TypedDict):")
            if d.doc:
                lines.append(f'    """{d.doc}"""')
            if not d.fields and not d.common:
                lines.append("    pass")
            for f in all_fields:
                ty = f"NotRequired[{f.ty.py}]" if f.optional else f.ty.py
                comment = f"  # {f.doc}" if f.doc else ""
                lines.append(f"    {f.name}: {ty}{comment}")
            lines.append("")
        else:  # pragma: no cover - exhaustive by construction
            raise TypeError(f"unknown def kind: {d!r}")
    return "\n".join(lines).rstrip() + "\n"


def render_typescript(defs: List[Def]) -> str:
    lines = [
        "// Typed wire shapes for every layout-tree node, leaf descriptor, and",
        "// `UiEvent`/activation a `QuiApp`/`QuiShellApp` render or event callback",
        "// exchanges with the native addon -- see `scripts/gen_wire_types.py` for",
        "// how this file is produced and what it deliberately leaves untyped.",
        "//",
        "// Every export here is `export type`/`export interface` -- erasable, no",
        "// runtime value -- so importing from this module costs nothing at",
        "// runtime even though Node's native TypeScript support strips rather",
        "// than compiles `.ts` (see `index.ts`'s own header comment).",
        "//",
        f"// {GENERATED_BANNER}",
        "",
    ]
    for d in defs:
        if isinstance(d, AliasDef):
            if d.doc:
                lines.append(f"/** {d.doc} */")
            lines.append(f"export type {d.name} = {d.ty.ts};")
            lines.append("")
        elif isinstance(d, ObjDef) and d.discriminated:
            # See `ObjDef.discriminated`'s doc: a union of single-required-
            # key object types, not one interface with optional properties
            # -- the shape TS's `"Tag" in value` actually narrows on.
            if d.doc:
                lines.append(f"/** {d.doc} */")
            common_ts = "".join(
                f" {cf.name}{'?' if cf.optional else ''}: {cf.ty.ts};" for cf in d.common
            )
            members = " | ".join(f"{{ {f.name}: {f.ty.ts};{common_ts} }}" for f in d.fields)
            lines.append(f"export type {d.name} = {members};")
            lines.append("")
        elif isinstance(d, ObjDef):
            if d.doc:
                lines.append(f"/** {d.doc} */")
            lines.append(f"export interface {d.name} {{")
            for f in d.fields:
                comment = f" // {f.doc}" if f.doc else ""
                lines.append(f"  {f.name}{'?' if f.optional else ''}: {f.ty.ts};{comment}")
            lines.append("}")
            lines.append("")
        else:  # pragma: no cover - exhaustive by construction
            raise TypeError(f"unknown def kind: {d!r}")
    return "\n".join(lines).rstrip() + "\n"


# ─── `docs/bindings-wire-format.md`: a Markdown field-table reference ──────
#
# Unlike `render_python`/`render_typescript` (each produces one whole,
# generator-owned file), the Markdown page mixes hand-written prose with a
# generated reference section -- see `render_doc_page`'s own doc for the
# splice this implies.


def _md_cell(text: str) -> str:
    """Escapes `text` for safe embedding inside a Markdown table cell --
    collapses an embedded newline to a space (a table row can't span lines)
    and escapes `|`, which a table parser would otherwise read as a cell
    boundary. A field's `.ts` type rendering (e.g. a union) can itself
    contain `|`, so this is needed for type cells, not just doc-comment
    cells."""
    return text.replace("\n", " ").replace("|", "\\|")


def _md_anchor(name: str) -> str:
    """A stable anchor id for `name`'s generated-reference heading, used by
    both the heading itself and the table-of-contents link to it --
    computed here rather than left to whatever heading-to-anchor heuristic
    a Markdown renderer happens to use, so the two never drift apart."""
    slug = re.sub(r"[^a-z0-9_]+", "-", name.lower()).strip("-")
    return f"wire-{slug}"


def _def_name(d: "Def") -> str:
    assert isinstance(d, (ObjDef, AliasDef))
    return d.name


def render_markdown_reference(defs: List[Def]) -> str:
    """Renders the generated half of `docs/bindings-wire-format.md`: a
    table of contents followed by one field table (or alias line) per
    [`DefJson`], in schema order -- the content `render_doc_page` splices
    between that page's `DOC_GENERATED_BEGIN`/`DOC_GENERATED_END` markers.

    A [`ObjDef.discriminated`] def (see that field's own doc) renders as a
    tag table instead of a field table -- exactly one tag's payload is
    present on the wire, so "Required" doesn't apply to its rows the way it
    does to an ordinary struct's fields; any `common` fields ride alongside
    whichever tag is set and get their own, ordinary field table beneath
    it.
    """
    lines = ["<!-- toc -->", ""]
    for d in defs:
        name = _def_name(d)
        lines.append(f"- [`{name}`](#{_md_anchor(name)})")
    lines.append("")
    lines.append("<!-- /toc -->")
    lines.append("")
    for d in defs:
        name = _def_name(d)
        lines.append(f'<a id="{_md_anchor(name)}"></a>')
        lines.append(f"#### `{name}`")
        lines.append("")
        if isinstance(d, AliasDef):
            if d.doc:
                lines.append(d.doc)
                lines.append("")
            lines.append(f"Alias for `{d.ty.ts}`.")
            lines.append("")
        elif isinstance(d, ObjDef) and d.discriminated:
            if d.doc:
                lines.append(d.doc)
                lines.append("")
            lines.append(
                "Exactly one of the tags below is present on the wire "
                "(a discriminated union):"
            )
            lines.append("")
            lines.append("| Tag | Payload type | Description |")
            lines.append("| --- | --- | --- |")
            for f in d.fields:
                lines.append(f"| `{f.name}` | `{_md_cell(f.ty.ts)}` | {_md_cell(f.doc)} |")
            lines.append("")
            if d.common:
                lines.append("Present alongside whichever tag above is set:")
                lines.append("")
                lines.append("| Field | Type | Required | Description |")
                lines.append("| --- | --- | --- | --- |")
                for f in d.common:
                    required = "no" if f.optional else "yes"
                    lines.append(
                        f"| `{f.name}` | `{_md_cell(f.ty.ts)}` | {required} | {_md_cell(f.doc)} |"
                    )
                lines.append("")
        elif isinstance(d, ObjDef):
            if d.doc:
                lines.append(d.doc)
                lines.append("")
            if not d.fields:
                lines.append("_(no fields)_")
                lines.append("")
            else:
                lines.append("| Field | Type | Required | Description |")
                lines.append("| --- | --- | --- | --- |")
                for f in d.fields:
                    required = "no" if f.optional else "yes"
                    lines.append(
                        f"| `{f.name}` | `{_md_cell(f.ty.ts)}` | {required} | {_md_cell(f.doc)} |"
                    )
                lines.append("")
        else:  # pragma: no cover - exhaustive by construction
            raise TypeError(f"unknown def kind: {d!r}")
    return "\n".join(lines).rstrip() + "\n"


def render_doc_page(current_text: str, defs: List[Def]) -> str:
    """Splices [`render_markdown_reference`]'s generated tables into
    `current_text` between its `DOC_GENERATED_BEGIN`/`DOC_GENERATED_END`
    markers, leaving every hand-written prose section around them
    untouched -- `docs/bindings-wire-format.md` is not a generator-owned
    file the way `wire.pyi`/`wire.d.ts` are, only that one section of it
    is.

    Raises if either marker is missing from `current_text`, rather than
    silently generating a page with no prose: a marker can only go missing
    by a hand-edit that removed it, which should fail loudly instead of
    quietly discarding everything written around it.
    """
    if DOC_GENERATED_BEGIN not in current_text or DOC_GENERATED_END not in current_text:
        raise ValueError(
            f"missing {DOC_GENERATED_BEGIN!r}/{DOC_GENERATED_END!r} markers -- "
            "docs/bindings-wire-format.md must keep both so the generated "
            "reference has somewhere to go"
        )
    before, rest = current_text.split(DOC_GENERATED_BEGIN, 1)
    _, after = rest.split(DOC_GENERATED_END, 1)
    generated = render_markdown_reference(defs)
    return f"{before}{DOC_GENERATED_BEGIN}\n\n{generated}\n{DOC_GENERATED_END}{after}"


# ─── `_quadraui.pyi`: pymethod stubs parsed straight from `lib.rs` ─────────
#
# This parser is deliberately narrow: it only needs to recover, per method,
# its name, parameter names/types/defaults, return type, and whether it is
# `#[new]`/`#[staticmethod]` -- never doc comments (this stub carries none)
# and never the method body. It works directly on `lib.rs`'s source text
# rather than on `syn`-parsed AST because this repo has no Rust-side tool
# in its build graph that already walks `#[pymethods]` the way
# `export_wire_schema` already walks `wire_schema.rs` for the data side --
# adding one would be a bigger lift than a depth-aware scan over a
# signature shape that PyO3 itself keeps simple (no generics, no `where`
# clauses, no trait-bound params).


@dataclass
class RustParam:
    name: str
    rust_type: str
    default: Optional[str] = None  # from `#[pyo3(signature = (...))]`


@dataclass
class RustMethod:
    name: str
    params: List[RustParam]
    return_type: Optional[str]  # None means `()` / no arrow at all
    is_static: bool = False
    is_new: bool = False


def _find_matching(text: str, open_idx: int, open_ch: str, close_ch: str) -> int:
    """The index of the bracket matching `open_ch` at `text[open_idx]`."""
    depth = 0
    i = open_idx
    n = len(text)
    while i < n:
        if text[i] == open_ch:
            depth += 1
        elif text[i] == close_ch:
            depth -= 1
            if depth == 0:
                return i
        i += 1
    raise ValueError(f"unbalanced {open_ch!r}/{close_ch!r} starting at offset {open_idx}")


def _split_top_level(text: str, sep: str = ",") -> List[str]:
    """Splits `text` on `sep`, ignoring any `sep` nested inside `<>`/`()`/
    `[]`/`{}` -- e.g. the inner comma in `Bound<'_, PyDict>` or
    `(String, Vec<String>)` never ends a parameter/argument early."""
    parts = []
    depth = 0
    current: List[str] = []
    for ch in text:
        if ch in "<([{":
            depth += 1
        elif ch in ">)]}":
            depth -= 1
        if ch == sep and depth == 0:
            parts.append("".join(current))
            current = []
        else:
            current.append(ch)
    tail = "".join(current)
    if tail.strip():
        parts.append(tail)
    return parts


def _parse_signature_defaults(attr_text: str) -> Dict[str, str]:
    """Extracts `name=default` pairs from a `#[pyo3(signature = (...))]`
    attribute's parenthesized argument list; a bare name with no `=` (a
    required argument) is simply absent from the result."""
    m = re.search(r"signature\s*=\s*\(", attr_text)
    if not m:
        return {}
    open_idx = m.end() - 1
    close_idx = _find_matching(attr_text, open_idx, "(", ")")
    inner = attr_text[open_idx + 1 : close_idx]
    defaults = {}
    for part in _split_top_level(inner):
        part = part.strip()
        if not part or "=" not in part:
            continue
        name, _, value = part.partition("=")
        defaults[name.strip()] = value.strip()
    return defaults


def _parse_params(params_text: str, defaults: Dict[str, str]) -> List[RustParam]:
    params = []
    for raw in _split_top_level(params_text):
        raw = raw.strip()
        if not raw:
            continue
        if raw in ("&self", "&mut self", "self"):
            params.append(RustParam(name="self", rust_type="self"))
            continue
        name, _, rust_type = raw.partition(":")
        name = name.strip()
        params.append(
            RustParam(name=name, rust_type=rust_type.strip(), default=defaults.get(name))
        )
    return params


def _parse_fn_at(src: str, fn_idx: int) -> Tuple[str, str, Optional[str], int]:
    """Parses one `fn name(...) [-> Ret] { ... }`/`;` starting at
    `src[fn_idx]` (the `f` of `fn`). Returns `(name, params_text,
    return_type, end_idx)`, where `end_idx` is just past the item (the
    matching `}` of its body, or the `;` of a body-less declaration)."""
    m = re.match(r"fn\s+(\w+)\s*", src[fn_idx:])
    if not m:
        raise ValueError(f"expected `fn` at offset {fn_idx}: {src[fn_idx:fn_idx + 40]!r}")
    name = m.group(1)
    paren_open = fn_idx + m.end()
    while src[paren_open].isspace():
        paren_open += 1
    paren_close = _find_matching(src, paren_open, "(", ")")
    params_text = src[paren_open + 1 : paren_close]
    j = paren_close + 1
    while src[j].isspace():
        j += 1
    return_type = None
    if src[j : j + 2] == "->":
        j += 2
        ret_start = j
        while src[j] not in "{;":
            j += 1
        return_type = src[ret_start:j].strip()
    while src[j] not in "{;":
        j += 1
    if src[j] == ";":
        end = j + 1
    else:
        end = _find_matching(src, j, "{", "}") + 1
    return name, params_text, return_type, end


def _parse_impl_block(src: str, open_brace_idx: int) -> List[RustMethod]:
    """Parses every `fn` directly inside one `impl ClassName { ... }` body
    (given the index of its opening `{`), skipping doc comments, plain
    comments, and every attribute except `#[new]`/`#[staticmethod]`/
    `#[pyo3(signature = (...))]` -- the three that change this stub's
    shape. Nested braces (a method body, a closure) are only ever skipped
    whole, via [`_find_matching`] / [`_parse_fn_at`], never scanned."""
    close_brace_idx = _find_matching(src, open_brace_idx, "{", "}")
    methods: List[RustMethod] = []
    i = open_brace_idx + 1
    pending_signature: Dict[str, str] = {}
    is_static = False
    is_new = False
    while i < close_brace_idx:
        ch = src[i]
        if ch.isspace():
            i += 1
            continue
        if src[i : i + 2] == "//":
            nl = src.find("\n", i)
            i = len(src) if nl == -1 else nl + 1
            continue
        if src[i : i + 2] == "/*":
            i = src.index("*/", i) + 2
            continue
        if ch == "#" and src[i + 1 : i + 2] == "[":
            close = _find_matching(src, i + 1, "[", "]")
            attr_text = src[i : close + 1]
            if "staticmethod" in attr_text:
                is_static = True
            if attr_text.strip() == "#[new]":
                is_new = True
            if "signature" in attr_text:
                pending_signature = _parse_signature_defaults(attr_text)
            i = close + 1
            continue
        if src[i : i + 2] == "fn" and not src[i + 2].isalnum():
            name, params_text, return_type, end = _parse_fn_at(src, i)
            methods.append(
                RustMethod(
                    name=name,
                    params=_parse_params(params_text, pending_signature),
                    return_type=return_type,
                    is_static=is_static,
                    is_new=is_new,
                )
            )
            pending_signature = {}
            is_static = False
            is_new = False
            i = end
            continue
        # Nothing else is expected directly inside a `#[pymethods]` impl
        # (a `const`, a private helper `fn` wrapped in its own `impl`
        # block elsewhere never reaches here) -- advance defensively
        # rather than looping forever on the unexpected.
        i += 1
    return methods


# The four `#[pymethods]` classes `lib.rs` has always declared. Any one of
# them parsing to zero methods is this parser's own signal that something
# went wrong upstream of it (a brace inside a string/char literal or
# comment confusing `_find_matching`'s raw-text brace count, an attribute
# between `#[pymethods]` and `impl` the detection regex doesn't expect) --
# [`parse_pymethods`] asserts this floor so that kind of silent truncation
# fails generation loudly instead of quietly shipping a thinner stub.
_EXPECTED_PYMETHODS_CLASSES = ("QuiApp", "QuiShellApp", "QuiAppWaker", "QuiAppActions")


def parse_pymethods(src: str, check_floor: bool = True) -> "Dict[str, List[RustMethod]]":
    """Every `#[pymethods] impl ClassName { ... }` block in `src`, in
    source order (so `_quadraui.pyi`'s class order mirrors `lib.rs`'s).

    `check_floor` enforces [`_EXPECTED_PYMETHODS_CLASSES`] all parsed a
    non-empty method list -- the default, since every real caller (this
    script's own `main`) parses the whole real `lib.rs` and should always
    see all four. A unit test parsing a small synthetic snippet missing
    most of them on purpose passes `check_floor=False`."""
    out: Dict[str, List[RustMethod]] = {}
    # An attribute (e.g. `#[cfg(...)]`) between `#[pymethods]` and `impl`
    # is allowed and skipped, rather than making the whole `impl` block
    # silently vanish from the match.
    for m in re.finditer(r"#\[pymethods\]\s*\n(?:#\[[^\]]*\]\s*\n)*impl\s+(\w+)\b[^{]*\{", src):
        cls = m.group(1)
        open_brace_idx = m.end() - 1
        out.setdefault(cls, []).extend(_parse_impl_block(src, open_brace_idx))
    if check_floor:
        for cls in _EXPECTED_PYMETHODS_CLASSES:
            if not out.get(cls):
                raise ValueError(
                    f"gen_wire_types.py: parsed zero methods for #[pymethods] impl {cls} -- "
                    "likely a brace inside a string/char literal or comment confusing the "
                    "brace-matching scan, or an attribute between #[pymethods] and impl"
                )
    return out


def parse_pyfunctions(src: str) -> List[RustMethod]:
    """Every module-level `#[pyfunction] fn ... { ... }` in `src`, in
    source order."""
    out = []
    for m in re.finditer(r"#\[pyfunction\]\s*\n", src):
        fn_idx = m.end()
        while src[fn_idx].isspace():
            fn_idx += 1
        name, params_text, return_type, _end = _parse_fn_at(src, fn_idx)
        out.append(
            RustMethod(name=name, params=_parse_params(params_text, {}), return_type=return_type)
        )
    return out


# PyO3's own built-in exception types, as named in a `create_exception!`
# call's base position, map to the plain Python name a `.pyi` stub
# actually names (`class Foo(Exception): ...`, never `class Foo
# (PyException): ...`). Extend this if `lib.rs` ever bases a
# `create_exception!` on another PyO3 built-in.
_PYO3_EXCEPTION_BASE_ALIASES = {"PyException": "Exception"}


def parse_create_exceptions(src: str) -> List[Tuple[str, str]]:
    """Every `create_exception!(_quadraui, Name, Base, "doc...")` call in
    `src`, as `(name, base)` pairs in source order. Parsed the same way
    `#[pymethods]`/`#[pyfunction]` are, so a new exception always shows up
    in the regenerated stub without a hand-maintained list to forget to
    update."""
    out = []
    for m in re.finditer(r"create_exception!\(\s*_quadraui\s*,\s*(\w+)\s*,\s*(\w+)\s*,", src):
        name, base = m.group(1), m.group(2)
        out.append((name, _PYO3_EXCEPTION_BASE_ALIASES.get(base, base)))
    return out


